export const parts = cars.flatMap((car) => {
  const selectedParts = [
    partTypes[(car.id - 1) % partTypes.length],
    partTypes[(car.id + 2) % partTypes.length],
    partTypes[(car.id + 5) % partTypes.length],
  ];

  return selectedParts.map((part, index) => {
    const id = (car.id - 1) * 3 + index + 1;

    return {
      id,
      carId: car.id,
      companyId: car.companyId,
      company: car.company,
      car: car.name,
      name: part.name,
      category: part.category,
      price: prices[(id - 1) % prices.length],
      currency: "UZS",
      rating: Number((4.5 + ((id * 7) % 5) / 10).toFixed(1)),
      stock: (id * 3) % 25 + 2,
      sku: `PG-${car.companyId}-${car.id}-${String(id).padStart(4, "0")}`,
      image: part.image,
    };
  });
});

